let priorAttempts = new Set<string>();
const stateFile = () => path.join(process.env.POCKET_BASE_E2E_DATA_DIR!, "demo.json");
test.beforeEach(async () => { const state = JSON.parse(await readFile(stateFile(), "utf8")); priorAttempts = new Set(state.attempts.map((a: {id:string})=>a.id)); });
test.afterEach(async () => {
  const state = JSON.parse(await readFile(stateFile(), "utf8"));
  for (const attempt of state.attempts) if (!priorAttempts.has(attempt.id)) attempt.at = "2000-01-01T00:00:00.000Z";
  const temporary = stateFile()+".allowance.tmp";
  await writeFile(temporary,JSON.stringify(state),{mode:0o600}); await rename(temporary,stateFile());
});
