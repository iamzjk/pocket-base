test("unfinished ideas can be discarded and failed discussion retries keep one user message",async({page})=>{
  await page.goto("/");
  await page.getByLabel("Describe your game idea").fill("Fictional busy model idea");
  await page.getByRole("button",{name:"Send",exact:true}).click();
  await expect(page.locator(".error-banner")).toContainText("busy");
  const id=new URL(page.url()).searchParams.get("idea")!;
  await expect(page.getByRole("button",{name:"Retry request",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Retry request",exact:true}).click();
  await expect(page.locator(".error-banner")).toContainText("busy");
  expect((await store().conversation(id))!.messages.filter(m=>m.kind==="user")).toHaveLength(1);
  await page.getByRole("button",{name:"Back to my studio"}).click();
  await page.getByRole("button",{name:"Discard Fictional busy model idea",exact:true}).click();
  await expect(page.getByRole("button",{name:"Continue Fictional busy model idea",exact:true})).toHaveCount(0);
});
